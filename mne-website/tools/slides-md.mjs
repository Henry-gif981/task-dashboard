// Write SLIDES.md (slide list with titles, content summary and morph keys) from the page itself.
//   node tools/slides-md.mjs [url]
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
const url = process.argv[2] || "http://localhost:5173/";
const require = createRequire(import.meta.url);
let pw;
try { pw = require("playwright"); } catch { pw = require(process.env.PLAYWRIGHT_PATH || "/opt/node22/lib/node_modules/playwright"); }
const browser = await pw.chromium.launch();
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
await page.goto(url, { waitUntil: "networkidle" });
const rows = await page.evaluate(() => [...document.querySelectorAll("#deck > .slide")].map((s, i, all) => {
  const keys = [...new Set([...s.querySelectorAll("[data-morph]")].map(e => e.dataset.morph))];
  const prev = i ? new Set([...all[i - 1].querySelectorAll("[data-morph]")].map(e => e.dataset.morph)) : new Set();
  const content = [];
  if (s.querySelector("table")) content.push([...s.querySelectorAll("caption")].map(c => c.textContent.replace(/\s+/g, " ").trim()).join("; "));
  if (s.querySelector("figcaption.fcap")) content.push([...s.querySelectorAll("figcaption.fcap")].map(c => c.textContent.replace(/\s+/g, " ").trim()).join("; "));
  const paras = s.querySelectorAll(".tx p, p.tx, .card p, .rec p, .refs li").length;
  if (paras) content.push(`${paras} text block${paras > 1 ? "s" : ""}`);
  if (s.dataset.web !== undefined) content.push("website slide");
  const bg = s.classList.contains("is-wash") ? "wash" : "paper";
  return { n: i + 1, id: s.id, title: s.dataset.title || "", bg, content: content.filter(Boolean).join(" · "), keys, shared: keys.filter(k => prev.has(k)) };
}));
await browser.close();
const lines = [
  "# SLIDES — generated by `node tools/slides-md.mjs`",
  "",
  `${rows.length} slides on a 1920×1080 stage. The counter "n / N" is computed by js/main.js from the DOM, so adding or removing a`,
  "slide needs no other change. Morph keys: see MORPH.md (keys shared with the previous slide are in **bold**).",
  "",
  "| # | id | Title | Bg | Content | Morph keys |",
  "|---|---|---|---|---|---|",
  ...rows.map(r => `| ${r.n} | \`${r.id}\` | ${r.title.replace(/\|/g, "/")} | ${r.bg} | ${r.content.replace(/\|/g, "/")} | ${r.keys.map(k => r.shared.includes(k) ? `**${k}**` : k).join(", ")} |`),
  "",
];
writeFileSync(resolve(import.meta.dirname, "../SLIDES.md"), lines.join("\n"));
console.log(`SLIDES.md: ${rows.length} slides`);
